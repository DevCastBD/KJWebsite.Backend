using Microsoft.EntityFrameworkCore;

namespace KJWebsite.BuildingBlocks.Auditing;

/// <summary>
/// One change to one audited row, written in the same transaction as the change itself. Append-only: nothing in the code base updates or
/// deletes these rows, the interceptor refuses to, and the PostgreSQL migration adds a trigger that refuses too.
/// </summary>
public sealed class AuditEvent
{
    /// <summary>Monotonic, so it doubles as the pagination cursor and the tie-breaker when two events share a timestamp.</summary>
    public long Id { get; set; }

    /// <summary>UTC. A DateTime (not DateTimeOffset) so every provider can range-filter it.</summary>
    public DateTime At { get; set; }

    public string Service { get; set; } = string.Empty;
    public string ActorId { get; set; } = string.Empty;
    public string? ActorEmail { get; set; }

    /// <summary>`create`, `update` or `delete`.</summary>
    public string Action { get; set; } = string.Empty;

    /// <summary>The entity type without its `Entity` suffix, for example `ContentItem`.</summary>
    public string Entity { get; set; } = string.Empty;

    /// <summary>Primary key, composite keys joined by `|`; `new` when the key is generated by the database on insert.</summary>
    public string EntityId { get; set; } = string.Empty;

    /// <summary>JSON of the previous values: every column when deleted, only the changed columns when updated, null when created.</summary>
    public string? Before { get; set; }

    /// <summary>JSON of the new values: every column when created, only the changed columns when updated, null when deleted.</summary>
    public string? After { get; set; }

    /// <summary>The request that caused it (`METHOD /path`), so the reason for a change is on the row.</summary>
    public string? Operation { get; set; }

    /// <summary>Groups the rows one request produced (one admin save usually touches several tables).</summary>
    public string? RequestId { get; set; }

    public string? Ip { get; set; }
    public string? UserAgent { get; set; }
}

public static class AuditModel
{
    /// <summary>Maps <see cref="AuditEvent"/> to `audit_events` with the indexes the query endpoint filters on.</summary>
    public static ModelBuilder ConfigureAudit(this ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<AuditEvent>(entity =>
        {
            entity.ToTable("audit_events");
            entity.HasKey(x => x.Id);
            entity.Property(x => x.Service).HasMaxLength(64).IsRequired();
            entity.Property(x => x.ActorId).HasMaxLength(64).IsRequired();
            entity.Property(x => x.ActorEmail).HasMaxLength(256);
            entity.Property(x => x.Action).HasMaxLength(16).IsRequired();
            entity.Property(x => x.Entity).HasMaxLength(64).IsRequired();
            entity.Property(x => x.EntityId).HasMaxLength(200).IsRequired();
            entity.Property(x => x.Operation).HasMaxLength(300);
            entity.Property(x => x.RequestId).HasMaxLength(64);
            entity.Property(x => x.Ip).HasMaxLength(64);
            entity.Property(x => x.UserAgent).HasMaxLength(256);
            entity.HasIndex(x => x.At);
            entity.HasIndex(x => new { x.Entity, x.EntityId, x.Id });
            entity.HasIndex(x => new { x.ActorId, x.Id });
            entity.HasIndex(x => x.RequestId);
        });
        return modelBuilder;
    }
}
